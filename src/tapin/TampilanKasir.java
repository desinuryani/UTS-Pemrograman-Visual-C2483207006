    private void btnHitungActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHitungActionPerformed
        try {
    String hargaText = txtHarga.getText()
        .replace("Rp", "")
        .replace(".", "")
        .trim();

    int harga = Integer.parseInt(hargaText);
    int jumlah = Integer.parseInt(txtJumlah.getText());

    if (jumlah <= 0) {
        javax.swing.JOptionPane.showMessageDialog(this,
            "Jumlah barang harus lebih dari 0!");
        return;
    }

    int total = harga * jumlah;

    txtTotal.setText(formatRupiah(total));

} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(this,
        "Pilih barang dan masukkan jumlah dengan benar!");
}
    }//GEN-LAST:event_btnHitungActionPerformed

    private void btnbayarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnbayarActionPerformed
       try {
        String totalText = txtTotal.getText()
            .replace("Rp", "")
            .replace(".", "")
            .trim();

        int total = Integer.parseInt(totalText);
        int pembayaran = Integer.parseInt(txtPembayaran.getText());

        if (pembayaran < total) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Uang pembayaran kurang!");
            return;
        }

        int kembalian = pembayaran - total;

        txtKembalian.setText(formatRupiah(kembalian));

        String struk = "       STRUK PEMBAYARAN TAPIN\n"
        + "--------------------------------\n"
        + "Nama Barang : " + txtNama.getText() + "\n"
        + "Harga       : " + txtHarga.getText() + "\n"
        + "Jumlah      : " + txtJumlah.getText() + "\n"
        + "--------------------------------\n"
        + "Total       : " + formatRupiah(total) + "\n"
        + "Pembayaran  : " + formatRupiah(pembayaran) + "\n"
        + "Kembalian   : " + formatRupiah(kembalian) + "\n"
        + "--------------------------------\n"
        + "       Terima kasih!\n"
        + "       Selamat menikmati";

javax.swing.JOptionPane.showMessageDialog(this,
    struk,
    "Struk Pembayaran",
    javax.swing.JOptionPane.INFORMATION_MESSAGE);

    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this,
            "Silakan hitung total dan masukkan uang pembayaran!");
    }
    
    }//GEN-LAST:event_btnbayarActionPerformed

    private void btnCetakStrukActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCetakStrukActionPerformed
        try {
        if (txtNama.getText().isEmpty()
                || txtTotal.getText().isEmpty()
                || txtKembalian.getText().isEmpty()) {

            javax.swing.JOptionPane.showMessageDialog(this,
                "Selesaikan transaksi terlebih dahulu!");
            return;
        }

        int pembayaran = Integer.parseInt(txtPembayaran.getText());

        String struk = "       STRUK PEMBAYARAN TAPIN\n"
                + "--------------------------------\n"
                + "Nama Barang : " + txtNama.getText() + "\n"
                + "Harga       : " + txtHarga.getText() + "\n"
                + "Jumlah      : " + txtJumlah.getText() + "\n"
                + "--------------------------------\n"
                + "Total       : " + txtTotal.getText() + "\n"
                + "Pembayaran  : " + formatRupiah(pembayaran) + "\n"
                + "Kembalian   : " + txtKembalian.getText() + "\n"
                + "--------------------------------\n"
                + "       Terima kasih!\n"
                + "       Selamat menikmati";

        javax.swing.JTextArea areaCetak =
                new javax.swing.JTextArea(struk);

        areaCetak.setFont(new java.awt.Font(
                "Monospaced", java.awt.Font.PLAIN, 12));

        areaCetak.print();

    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this,
            "Data pembayaran tidak valid!");
    } catch (java.awt.print.PrinterException e) {
        javax.swing.JOptionPane.showMessageDialog(this,
            "Gagal mencetak struk!");
    }
    }//GEN-LAST:event_btnCetakStrukActionPerformed

